function replaceMobileText(value: string, language: AppLanguage): string {
  if (language !== 'en' || typeof value !== 'string') return value;
  return MOBILE_ENGLISH_UI_TEXT[value] || value;
}

export function translateUiText(value: string, language: AppLanguage = 'vi'): string {
  if (language !== 'en' || typeof value !== 'string') return value;
  const shared = translateSharedUiText(value, language);
  return shared === value ? replaceMobileText(value, language) : shared;
}

export function createTranslator(language: AppLanguage) {
  return (value: string) => translateUiText(value, language);
}
